# Bundles the worker for the Cloudflare dashboard editor: the engine, the online tables and the score boards in one file.
import os
d = os.path.dirname(os.path.abspath(__file__))
eng = open(os.path.join(d, '..', 'assets', 'kirilii', 'engine.js')).read()
out = ('// GENERATED by worker/build.py, edit the sources instead\n'
       'const Kirilii = (function () { const module = { exports: {} }; ' + eng + '\n return module.exports; })();\n\n'
       + open(os.path.join(d, 'scores.js')).read() + '\n' + open(os.path.join(d, 'kirilii-online.js')).read())
open(os.path.join(d, 'dist.js'), 'w').write(out)
print('dist.js', len(out))
